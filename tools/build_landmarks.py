"""Build src/shared/WorldData/Landmarks.lua: each landmark's outline (studs), its
oriented box, and the county building ids under it (built by LandmarkBuilder).

    python tools/build_landmarks.py
"""
import json
import math
from pathlib import Path

from shapely.geometry import shape
from shapely.ops import transform
from shapely.strtree import STRtree

ROOT = Path(__file__).resolve().parents[1]
DATA = Path(r"E:\ChesterWorld\Data")
OUT = ROOT / "src" / "shared" / "WorldData" / "Landmarks.lua"

# key -> OSM area name (04_POI/osm_poi_areas.geojson or 10_Addresses areas)
LANDMARKS = {
    "city_hall": "Chester City Hall",
    "subaru_park": "Subaru Park",
    "harrahs": "Harrah's Philadelphia",
    "old_main": "Old Main",
    "wolfgram_library": "Wolfgram Memorial Library",
    "quick_stadium": "Leslie C. Quick Jr. Stadium",
    "wharf": "The Wharf at Rivertown",
    "chester_high": "Chester High School",
    "crozer_north": "Crozer North Campus",
    "deshong_museum": "Alfred O. Deshong Park Museum",
    "crozer_building": "Crozer Building",
    "barry_bridge": "Commodore Barry Bridge",
}


def studs(lon, lat):
    mx = lon * 20037508.34 / 180.0
    my = math.log(math.tan((90.0 + lat) * math.pi / 360.0)) * 6378137.0
    return (mx + 8397592 - 6347.889) * 3, -(my - 4837229 - 7201.973) * 3


def to_studs(geom):
    return transform(lambda xs, ys, zs=None: tuple(zip(*[studs(x, y) for x, y in zip(xs, ys)])), geom)


def oriented(poly):
    rect = poly.minimum_rotated_rectangle
    pts = list(rect.exterior.coords)[:4]
    e1 = (pts[1][0] - pts[0][0], pts[1][1] - pts[0][1])
    e2 = (pts[2][0] - pts[1][0], pts[2][1] - pts[1][1])
    l1, l2 = math.hypot(*e1), math.hypot(*e2)
    along = e1 if l1 >= l2 else e2
    c = rect.centroid
    return [round(c.x, 1), round(c.y, 1), round(max(l1, l2), 1), round(min(l1, l2), 1),
            round(-math.degrees(math.atan2(along[1], along[0])), 1)]


def main():
    areas = {}
    for path in ("04_POI/osm_poi_areas.geojson", "10_Addresses/osm_address_areas.geojson"):
        for f in json.loads((DATA / path).read_text(encoding="utf-8"))["features"]:
            name = f["properties"].get("name")
            if name and name not in areas:
                areas[name] = to_studs(shape(f["geometry"]).buffer(0))
    # Harrah's harness track: OSM maps it as an unnamed horse_racing sports centre
    tracks = [to_studs(shape(f["geometry"]).buffer(0))
              for f in json.loads((DATA / "11_LandUse" / "osm_landuse_areas.geojson").read_text(encoding="utf-8"))["features"]
              if f["properties"].get("sport") == "horse_racing"]
    if tracks:
        areas["__racetrack"] = max(tracks, key=lambda g: g.area)
        LANDMARKS["racetrack"] = "__racetrack"
    county = json.loads((DATA / "13_RegionalMaster" / "regional_buildings_base.geojson").read_text(encoding="utf-8"))["features"]
    polys = [to_studs(shape(f["geometry"]).buffer(0)) for f in county]
    ids = [str(f["properties"]["OBJECTID"]) for f in county]
    tree = STRtree(polys)
    lines = ["-- Generated by tools/build_landmarks.py (studs). Built by LandmarkBuilder.server.lua.", "return {"]
    for key, name in LANDMARKS.items():
        area = areas.get(name)
        if area is None:
            print("missing", key, name)
            continue
        if area.geom_type == "MultiPolygon":
            area = max(area.geoms, key=lambda g: g.area)
        inside = [ids[i] for i in tree.query(area, predicate="intersects")
                  if polys[i].intersection(area).area > 0.5 * polys[i].area]
        outline = [round(v, 1) for x, z in list(area.simplify(3).exterior.coords)[:-1] for v in (x, z)]
        lines.append('\t%s={name="%s",box={%s},outline={%s},buildings={%s}},' % (
            key, name.replace('"', '\\"'), ",".join(map(str, oriented(area))), ",".join(map(str, outline)),
            ",".join('"%s"' % i for i in inside)))
        print(key, "buildings", len(inside), "box", oriented(area))
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
