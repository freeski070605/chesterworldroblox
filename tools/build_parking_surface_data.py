"""Export explicitly mapped OSM surface parking areas in Roblox studs.

Run: python tools/build_parking_surface_data.py
The output contains polygons, not pavement Parts. Runtime paints existing
Terrain voxels without changing their occupancy or elevation.
"""

import math
import json
from pathlib import Path

import osmium
from shapely.geometry import Polygon, shape
from shapely.ops import transform


ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path('E:/ChesterWorld/Data/03_OSM/chester_world.osm.pbf')
OUTPUT = ROOT / 'src/server/World/ParkingSurfaceData.lua'
GROUND_SOURCE = Path('E:/ChesterWorld/Data/11_LandUse/osm_landuse_areas.geojson')
GROUND_OUTPUT = ROOT / 'src/server/World/MappedGroundSurfaceData.lua'


def studs(lon, lat):
    mx = lon * 20037508.34 / 180.0
    my = math.log(math.tan((90.0 + lat) * math.pi / 360.0)) * 6378137.0
    return (mx + 8397592 - 6347.889) * 3, -(my - 4837229 - 7201.973) * 3


class Parking(osmium.SimpleHandler):
    def __init__(self):
        super().__init__()
        self.lots = []
        self.rejected = 0

    def way(self, way):
        tags = dict(way.tags)
        if tags.get('amenity') != 'parking' or tags.get('parking', 'surface') != 'surface':
            return
        if len(way.nodes) < 4 or way.nodes[0].ref != way.nodes[-1].ref:
            return
        try:
            polygon = Polygon([studs(node.lon, node.lat) for node in way.nodes]).buffer(0)
        except (ValueError, osmium.InvalidLocationError):
            self.rejected += 1
            return
        if polygon.is_empty or polygon.area < 400:
            self.rejected += 1
            return
        if polygon.geom_type == 'MultiPolygon':
            polygon = max(polygon.geoms, key=lambda part: part.area)
        polygon = polygon.simplify(2, preserve_topology=True)
        if polygon.interiors or len(polygon.exterior.coords) > 250:
            self.rejected += 1
            return
        surface = tags.get('surface', '').lower()
        material = 'Gravel' if surface in {'gravel', 'fine_gravel', 'compacted', 'dirt', 'ground'} else 'Asphalt'
        coords = [round(value, 1) for xy in list(polygon.exterior.coords)[:-1] for value in xy]
        self.lots.append((way.id, material, coords))


def main():
    reader = Parking()
    reader.apply_file(str(SOURCE), locations=True)
    rows = [
        '-- Generated by tools/build_parking_surface_data.py from local OSM parking ways.',
        '-- Explicit amenity=parking, parking=surface only; existing Terrain geometry is preserved.',
        'return {',
    ]
    for ident, material, coords in sorted(reader.lots):
        packed = ','.join(f'{value:g}' for value in coords)
        rows.append(f'    {{id={ident},material="{material}",outline={{{packed}}}}},')
    rows.append('}')
    OUTPUT.write_text('\n'.join(rows) + '\n', encoding='utf-8')
    print(f'parking lots={len(reader.lots)} rejected={reader.rejected} bytes={OUTPUT.stat().st_size}')

    treatments = []
    for feature in json.loads(GROUND_SOURCE.read_text(encoding='utf-8'))['features']:
        props = feature['properties']
        category = props.get('landuse')
        if category not in {'grass', 'meadow', 'brownfield'}:
            continue
        geometry = transform(lambda x, y, z=None: studs(x, y), shape(feature['geometry']).buffer(0))
        if geometry.geom_type == 'MultiPolygon':
            geometry = max(geometry.geoms, key=lambda part: part.area)
        if geometry.is_empty or geometry.area < 400:
            continue
        geometry = geometry.simplify(2, preserve_topology=True)
        if geometry.interiors or len(geometry.exterior.coords) > 250:
            continue
        material = 'Ground' if category == 'brownfield' else 'Grass'
        coords = [round(value, 1) for xy in list(geometry.exterior.coords)[:-1] for value in xy]
        treatments.append((props.get('osm_id'), material, coords))
    ground_rows = [
        '-- Generated by tools/build_parking_surface_data.py from explicit OSM landuse polygons.',
        '-- Painted before mapped parking; no generic parcel inference.',
        'return {',
    ]
    for ident, material, coords in sorted(treatments):
        packed = ','.join(f'{value:g}' for value in coords)
        ground_rows.append(f'    {{id={ident},material="{material}",outline={{{packed}}}}},')
    ground_rows.append('}')
    GROUND_OUTPUT.write_text('\n'.join(ground_rows) + '\n', encoding='utf-8')
    print(f'mapped ground areas={len(treatments)} bytes={GROUND_OUTPUT.stat().st_size}')


if __name__ == '__main__':
    main()
