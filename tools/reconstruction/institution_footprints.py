"""Export exact county footprints and photo-ray anchors for the photo-matched
institution models (src/server/World/InstitutionFootprints.lua).

For every building whose spec has a `poly={...}` block (or is listed on the
command line) this writes:
  * poly  - the county footprint outer ring in tile source metres
            (EPSG:3857 + offset), lightly simplified
  * hits  - for every reference photo of the building (front photo and the
            extra views in extra_views.csv), the point where the photo's
            centre ray meets the footprint, and the camera position.
            Keys are "<pano id first 8 chars>_<heading int>", so a spec can
            place an entrance or a sign where a named photo shows it.

    py -3 tools/reconstruction/institution_footprints.py [ids...]
"""
import csv
import json
import math
import re
import sys
from pathlib import Path

from shapely.geometry import LineString, Point, Polygon

ROOT = Path(__file__).resolve().parents[2]
DATA = Path(r"E:\ChesterWorld\Data")
GSV = DATA / "25_GoogleStreetView_Buildings"
SPEC = ROOT / "src" / "server" / "World" / "InstitutionReconstruction.lua"
OUT = ROOT / "src" / "server" / "World" / "InstitutionFootprints.lua"
X_OFFSET, Z_OFFSET = 8397592.0, -4837229.0


def src(lon, lat):
    return (lon * 20037508.34 / 180 + X_OFFSET,
            math.log(math.tan((90 + lat) * math.pi / 360)) * 6378137 + Z_OFFSET)


def wanted(argv):
    if argv:
        return set(argv)
    text = SPEC.read_text(encoding="utf-8")
    ids = set()
    for m in re.finditer(r'\n\["(\d+)"\]=\{(.*?)(?=\n\["|\n-{6}|\n\}\s*$)', text, re.S):
        if re.search(r"\bpoly=\{", m.group(2)):
            ids.add(m.group(1))
    return ids


def photos(bid):
    rows = []
    with open(GSV / "manifest.csv", encoding="utf-8-sig") as fh:
        for r in csv.DictReader(fh):
            if r["objectid"] == bid and r["status"] == "ok":
                rows.append((r["pano_id"], float(r["camera_lat"]), float(r["camera_lon"]), float(r["camera_heading_deg"])))
    log = GSV / "extra_views.csv"
    if log.exists():
        with open(log, encoding="utf-8") as fh:
            for r in csv.DictReader(fh):
                if r["objectid"] == bid:
                    rows.append((r["pano_id"], float(r["lat"]), float(r["lon"]), float(r["heading"])))
    return rows


def main():
    ids = wanted(sys.argv[1:])
    feats = json.loads((DATA / "13_RegionalMaster" / "regional_buildings_base.geojson").read_text(encoding="utf-8"))["features"]
    geo = {str(f["properties"]["OBJECTID"]): f["geometry"] for f in feats if str(f["properties"]["OBJECTID"]) in ids}
    out = ["-- GENERATED by tools/reconstruction/institution_footprints.py - do not edit.",
           "-- County footprint rings (tile source metres) and photo-ray anchors for the",
           "-- photo-matched institution models (InstitutionPoly.lua).",
           "return {"]
    for bid in sorted(ids, key=int):
        g = geo.get(bid)
        if not g:
            print("no footprint", bid)
            continue
        ring = g["coordinates"][0] if g["type"] == "Polygon" else max(g["coordinates"], key=lambda p: len(p[0]))[0]
        pg = Polygon([src(lon, lat) for lon, lat, *_ in ring]).simplify(0.25)
        if not pg.exterior.is_ccw:
            pg = Polygon(list(pg.exterior.coords)[::-1])
        pts = list(pg.exterior.coords)[:-1]
        hits = {}
        for pano, lat, lon, heading in photos(bid):
            cx, cz = src(lon, lat)
            t = math.radians(heading)
            ray = LineString([(cx, cz), (cx + math.sin(t) * 400, cz + math.cos(t) * 400)])
            inter = ray.intersection(pg.exterior)
            if inter.is_empty:
                continue
            cands = [inter] if inter.geom_type == "Point" else [g2 for g2 in getattr(inter, "geoms", []) if g2.geom_type == "Point"]
            if not cands:
                continue
            hit = min(cands, key=lambda p: p.distance(Point(cx, cz)))
            hits[f"{pano[:8]}_{int(heading)}"] = (round(hit.x, 2), round(hit.y, 2), round(cx, 2), round(cz, 2))
        out.append(f'["{bid}"]={{poly={{' + ",".join(f"{{{x:.2f},{z:.2f}}}" for x, z in pts) + "},")
        out.append("\thits={" + ",".join(f'["{k}"]={{{v[0]},{v[1]},{v[2]},{v[3]}}}' for k, v in sorted(hits.items())) + "}},")
        print(bid, len(pts), "vertices", len(hits), "anchors")
    out.append("}")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(OUT)


if __name__ == "__main__":
    main()
