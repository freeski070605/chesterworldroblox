"""One-pass, reproducible county-footprint and local-photo neighborhood index."""
import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = Path(r"E:\ChesterWorld\Data")
OUT = ROOT / "docs" / "9th_kerlin_footprints.csv"
SCOPE_MODULE = ROOT / "src/server/World/NeighborhoodScope.lua"
# W 9th from Lincoln to the Concord/five-point junction, both adjoining
# 8th-to-10th blocks. Source WGS84 envelope; boundary parcels included.
WEST, EAST, SOUTH, NORTH = -75.37465, -75.37020, 39.84720, 39.84870


def in_scope(feature):
    coords = feature["geometry"]["coordinates"]
    rings = coords if feature["geometry"]["type"] == "Polygon" else [r for p in coords for r in p]
    return any(WEST <= lon <= EAST and SOUTH <= lat <= NORTH for ring in rings for lon, lat, *_ in ring)


def main():
    geo = json.loads((DATA / "13_RegionalMaster" / "regional_buildings_base.geojson").read_text())
    photos = {}
    for folder in ("25_GoogleStreetView_Buildings", "24_BuildingImagery_Mapillary"):
        with (DATA / folder / "manifest.csv").open(newline="", encoding="utf-8-sig") as f:
            for row in csv.DictReader(f):
                photos.setdefault(str(row["objectid"]), []).append((folder, row))
    reviewed = set(re.findall(r'\["([0-9]+)"\]=', (ROOT / "src/server/World/BuildingReviewOverrides.lua").read_text()))
    rows = []
    for feature in geo["features"]:
        if not in_scope(feature):
            continue
        p = feature["properties"]
        oid = str(p["OBJECTID"])
        available = [f"{folder}/{r['path'].replace(chr(92), '/')}" for folder, r in photos.get(oid, []) if (DATA / folder / r["path"]).is_file()]
        rows.append(dict(id=oid, lon=p["center_lon"], lat=p["center_lat"], address=p.get("address", ""),
                         use=p.get("building_use", ""), archetype=p.get("generator_archetype", ""),
                         height_m=p.get("height_m", ""), area_sqm=p.get("area_sqm", ""),
                         photo_count=len(available), photos=";".join(available),
                         review="photo_verified" if oid in reviewed else "unresolved_photo_match" if available else "no_local_photo"))
    rows.sort(key=lambda r: (float(r["lon"]), float(r["lat"]), int(r["id"])))
    with OUT.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=rows[0].keys())
        writer.writeheader()
        writer.writerows(rows)
    SCOPE_MODULE.write_text("-- Generated by tools/reconstruction/kerlin_neighborhood.py from county footprints.\n"
                            "-- Unreviewed IDs keep source geometry and receive no facade claims.\nreturn {\n"
                            + "".join(f'    ["{r["id"]}"]=true,\n' for r in rows) + "}\n")
    print(f"{len(rows)} footprints, {sum(bool(r['photo_count']) for r in rows)} with a local photo: {OUT}")
    print("photo IDs:", " ".join(r["id"] for r in rows if r["photo_count"]))


def sheets():
    from PIL import Image, ImageDraw
    with OUT.open(newline="", encoding="utf-8") as f:
        selected = [r for r in csv.DictReader(f) if r["photos"]]
    target = ROOT / "docs" / "kerlin_photo_review"
    target.mkdir(exist_ok=True)
    for start in range(0, len(selected), 16):
        sheet = Image.new("RGB", (1600, 1200), "#eeeeee")
        draw = ImageDraw.Draw(sheet)
        for i, row in enumerate(selected[start:start + 16]):
            path = DATA / row["photos"].split(";")[0]
            with Image.open(path) as image:
                image.thumbnail((390, 260))
                x, y = (i % 4) * 400, (i // 4) * 300
                sheet.paste(image, (x + (400-image.width)//2, y))
                draw.text((x + 8, y + 263), f"{row['id']} {row['address'][:34]}", fill="black")
        out = target / f"sheet_{start//16 + 1}.jpg"
        sheet.save(out, quality=85)
        print(out)


def aerial():
    from PIL import Image, ImageDraw
    from pyproj import Transformer
    transform = Transformer.from_crs(4326, 3857, always_xy=True).transform
    # This whole 9th Street reach lies in the 2025 DVRPC 1 m source tile.
    source = DATA / "19_Aerial" / "dvrpc2025_1m_-8392000_4842000.jpg"
    image = Image.open(source).convert("RGB")
    geo = json.loads((DATA / "13_RegionalMaster" / "regional_buildings_base.geojson").read_text())
    x0, y0, x1, y1 = -8390680, 4843700, -8390040, 4844010
    box = (round(x0 + 8392000), round(2000-(y1-4842000)), round(x1 + 8392000), round(2000-(y0-4842000)))
    crop = image.crop(box).resize(((box[2]-box[0])*3, (box[3]-box[1])*3))
    draw = ImageDraw.Draw(crop)
    for f in geo["features"]:
        if not in_scope(f): continue
        coords = f["geometry"]["coordinates"][0]
        xy = [((transform(lon,lat)[0]-x0)*3, (y1-transform(lon,lat)[1])*3) for lon,lat,*_ in coords]
        draw.line(xy, fill="yellow", width=2)
        lon,lat=f["properties"]["center_lon"],f["properties"]["center_lat"]
        xx,yy=transform(lon,lat)
        draw.text(((xx-x0)*3,(y1-yy)*3),str(f["properties"]["OBJECTID"]),fill="yellow",stroke_width=2,stroke_fill="black")
    out=ROOT/"docs"/"kerlin_photo_review"/"aerial_footprints.jpg"
    crop.save(out,quality=90)
    print(out)


if __name__ == "__main__":
    import sys
    aerial() if "--aerial" in sys.argv else sheets() if "--sheets" in sys.argv else main()
