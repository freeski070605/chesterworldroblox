"""Build src/shared/WorldData/Parks.lua from the county parks and OSM leisure areas.

    python tools/build_parks.py

Everything is emitted in Roblox studs. Parks: name, simplified outline, an inset
walking loop. Features (pitches, playgrounds, pools, tracks, cemeteries): an
oriented rectangle {cx, cz, length, width, yaw} plus kind/sport; cemeteries also
keep their outline. Built at runtime by src/server/World/ParkBuilder.server.lua.
"""
import json
import math
from pathlib import Path

from shapely.geometry import shape
from shapely.ops import transform, unary_union

ROOT = Path(__file__).resolve().parents[1]
DATA = Path(r"E:\ChesterWorld\Data")
PARKS = DATA / "05_Official_POI" / "delco_parks.geojson"
LANDUSE = DATA / "11_LandUse" / "osm_landuse_areas.geojson"
OUT = ROOT / "src" / "shared" / "WorldData" / "Parks.lua"


def studs(lon, lat):
    mx = lon * 20037508.34 / 180.0
    my = math.log(math.tan((90.0 + lat) * math.pi / 360.0)) * 6378137.0
    return (mx + 8397592 - 6347.889) * 3, -(my - 4837229 - 7201.973) * 3


def to_studs(geom):
    return transform(lambda xs, ys, zs=None: tuple(zip(*[studs(x, y) for x, y in zip(xs, ys)])), geom)


def biggest(geom):
    if geom.geom_type == "MultiPolygon":
        return max(geom.geoms, key=lambda g: g.area)
    return geom


def oriented(poly):
    """{cx, cz, length, width, yaw} of the minimum rotated rectangle; yaw is the
    Roblox Y rotation (degrees) that puts local +X along the long side."""
    rect = poly.minimum_rotated_rectangle
    pts = list(rect.exterior.coords)[:4]
    e1 = (pts[1][0] - pts[0][0], pts[1][1] - pts[0][1])
    e2 = (pts[2][0] - pts[1][0], pts[2][1] - pts[1][1])
    l1, l2 = math.hypot(*e1), math.hypot(*e2)
    along = e1 if l1 >= l2 else e2
    theta = math.atan2(along[1], along[0])
    c = rect.centroid
    return [round(c.x, 1), round(c.y, 1), round(max(l1, l2), 1), round(min(l1, l2), 1), round(-math.degrees(theta), 1)]


def ring(poly, tolerance=6):
    simple = poly.simplify(tolerance, preserve_topology=True)
    return [round(v, 1) for x, z in list(simple.exterior.coords)[:-1] for v in (x, z)]


def lua(value):
    if isinstance(value, str):
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, list):
        return "{" + ",".join(lua(v) for v in value) + "}"
    if isinstance(value, dict):
        return "{" + ",".join(f"{k}={lua(v)}" for k, v in value.items() if v is not None) + "}"
    raise TypeError(value)


def main():
    parks = []
    for f in json.loads(PARKS.read_text(encoding="utf-8"))["features"]:
        poly = biggest(to_studs(shape(f["geometry"]).buffer(0)))
        if poly.area < 300:
            continue
        loop = poly.buffer(-18)
        loop = biggest(loop) if not loop.is_empty and loop.area > 2500 else None
        parks.append({
            "name": (f["properties"].get("PARK_NAME") or "").strip() or None,
            "outline": ring(poly),
            "loop": ring(loop, 10) if loop else None,
            "area": round(poly.area),
        })
    features = []
    for f in json.loads(LANDUSE.read_text(encoding="utf-8"))["features"]:
        p = f["properties"]
        kind = p.get("leisure") or p.get("landuse") or p.get("amenity")
        sport = (p.get("sport") or "").split(";")[0] or None
        if kind not in ("pitch", "playground", "swimming_pool", "track", "cemetery", "grave_yard", "park"):
            continue
        poly = biggest(to_studs(shape(f["geometry"]).buffer(0)))
        if poly.area < 60:
            continue
        if kind == "park":
            # OSM parks the county layer lacks
            if any(shape_contains(pk, poly) for pk in parks):
                continue
            parks.append({"name": None, "outline": ring(poly), "loop": None, "area": round(poly.area)})
            continue
        if kind == "grave_yard":
            kind = "cemetery"
        item = {"kind": kind, "sport": sport, "box": oriented(poly)}
        if kind == "cemetery":
            item["outline"] = ring(poly, 4)
        features.append(item)
    lines = ["-- Generated by tools/build_parks.py (studs). Built by ParkBuilder.server.lua.",
             "return {", "\tparks = {"]
    lines += ["\t\t" + lua(p) + "," for p in parks]
    lines += ["\t},", "\tfeatures = {"]
    lines += ["\t\t" + lua(item) + "," for item in features]
    lines += ["\t},", "}"]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    kinds = {}
    for item in features:
        key = item["kind"] + (":" + item["sport"] if item["sport"] else "")
        kinds[key] = kinds.get(key, 0) + 1
    print("parks", len(parks), "named", sum(1 for p in parks if p["name"]), "features", len(features), kinds)


def shape_contains(park, poly):
    from shapely.geometry import Polygon
    pts = park["outline"]
    outline = Polygon(list(zip(pts[0::2], pts[1::2])))
    return outline.buffer(10).contains(poly.centroid)


if __name__ == "__main__":
    main()
