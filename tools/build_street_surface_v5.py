#!/usr/bin/env python3
from __future__ import annotations

import json
import math
import shutil
from pathlib import Path

from shapely.geometry import GeometryCollection, LineString, MultiLineString, MultiPolygon, Polygon, box, shape
from shapely.ops import triangulate, unary_union

ROOT = Path(r"E:\ChesterWorld")
PROJECT = Path(r"E:\code\chesterworld-roblox")
TILE_ROOT = ROOT / "Data" / "18_RegionalTiles_StreetV3"
TILES_DIR = TILE_ROOT / "Tiles"
OUT_DIR = ROOT / "Data" / "20_StreetSurfaceV5"
LUA_DIR = PROJECT / "src" / "shared" / "StreetSurfaceTiles"
REPORT = OUT_DIR / "street_surface_v5_report.json"

STUDS_PER_METER = 3.0
CENTER_X_M = 6347.889
CENTER_Z_M = 7201.973
SIMPLIFY_M = 0.12
MAX_EDGE_M = 7.0
MIN_TRIANGLE_AREA_M2 = 0.025
MAX_VERTICES_PER_TILE = 50000
MAX_TOTAL_TRIANGLES = 250000
BRIDGE_TRUE = {"yes", "true", "1"}
TUNNEL_TRUE = {"yes", "true", "1"}


def load_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def clean(value):
    if value is None:
        return ""
    text = str(value).strip().lower()
    return "" if text in {"", "none", "null", "nan"} else text


def road_width(props):
    for key in ("generator_width_m", "generator_render_width_m", "width_m", "width"):
        try:
            value = float(props.get(key))
            if 1.0 <= value <= 80.0:
                return value
        except Exception:
            pass
    return 6.0


def lines_from_geom(geom):
    if geom is None or geom.is_empty:
        return []
    if isinstance(geom, LineString):
        return [geom]
    if isinstance(geom, MultiLineString):
        return [g for g in geom.geoms if not g.is_empty]
    if isinstance(geom, GeometryCollection):
        out = []
        for g in geom.geoms:
            out.extend(lines_from_geom(g))
        return out
    return []


def polygons_from_geom(geom):
    if geom is None or geom.is_empty:
        return []
    if isinstance(geom, Polygon):
        return [geom]
    if isinstance(geom, MultiPolygon):
        return [g for g in geom.geoms if not g.is_empty]
    if isinstance(geom, GeometryCollection):
        out = []
        for g in geom.geoms:
            out.extend(polygons_from_geom(g))
        return out
    return []


def densify_ring(coords, max_edge):
    coords = list(coords)
    if len(coords) < 2:
        return coords
    result = []
    for i in range(len(coords) - 1):
        ax, ay = coords[i][:2]
        bx, by = coords[i + 1][:2]
        dx = bx - ax
        dy = by - ay
        dist = math.hypot(dx, dy)
        steps = max(1, int(math.ceil(dist / max_edge)))
        for step in range(steps):
            t = step / steps
            result.append((ax + dx * t, ay + dy * t))
    result.append(tuple(coords[-1][:2]))
    return result


def densify_polygon(poly):
    exterior = densify_ring(poly.exterior.coords, MAX_EDGE_M)
    holes = [densify_ring(ring.coords, MAX_EDGE_M) for ring in poly.interiors]
    result = Polygon(exterior, holes)
    if not result.is_valid:
        result = result.buffer(0)
    return result


def triangulate_polygon(poly):
    result = []
    if poly.is_empty or poly.area < MIN_TRIANGLE_AREA_M2:
        return result
    try:
        poly = poly.simplify(SIMPLIFY_M, preserve_topology=True)
    except Exception:
        pass
    poly = densify_polygon(poly)
    for tri in triangulate(poly):
        if tri.is_empty or tri.area < MIN_TRIANGLE_AREA_M2:
            continue
        try:
            intersection_area = tri.intersection(poly).area
        except Exception:
            continue
        if tri.area <= 0 or intersection_area / tri.area < 0.985:
            continue
        if not poly.covers(tri.representative_point()):
            continue
        coords = list(tri.exterior.coords)
        if len(coords) >= 4:
            result.append([tuple(coords[0][:2]), tuple(coords[1][:2]), tuple(coords[2][:2])])
    return result


def roblox_xz(local_x, local_z):
    return ((local_x - CENTER_X_M) * STUDS_PER_METER, -(local_z - CENTER_Z_M) * STUDS_PER_METER)


def lua_num(value):
    return f"{float(value):.3f}"


def write_tile_module(path, tile_id, origin_x, origin_z, vertices, triangles):
    lines = [
        "-- Generated by build_street_surface_v5.py",
        "return {",
        f'\ttileId = "{tile_id}",',
        f"\toriginX = {lua_num(origin_x)},",
        f"\toriginZ = {lua_num(origin_z)},",
        "\tvertices = {",
    ]
    flat = []
    for x, z in vertices:
        flat.extend((x, z))
    chunk = []
    for value in flat:
        chunk.append(lua_num(value))
        if len(chunk) >= 16:
            lines.append("\t\t" + ",".join(chunk) + ",")
            chunk = []
    if chunk:
        lines.append("\t\t" + ",".join(chunk) + ",")
    lines += ["\t},", "\ttriangles = {"]
    flat_t = []
    for a, b, c in triangles:
        flat_t.extend((a, b, c))
    chunk = []
    for value in flat_t:
        chunk.append(str(int(value)))
        if len(chunk) >= 24:
            lines.append("\t\t" + ",".join(chunk) + ",")
            chunk = []
    if chunk:
        lines.append("\t\t" + ",".join(chunk) + ",")
    lines += ["\t},", "}", ""]
    path.write_text("\n".join(lines), encoding="utf-8")


def main():
    print("=" * 92)
    print("CHESTERWORLD STREET SURFACE V5 - CONTINUOUS TILE ASPHALT MESH DATA")
    print("=" * 92)
    if not TILES_DIR.exists():
        raise SystemExit(f"Missing Street V3 tiles: {TILES_DIR}")
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    if LUA_DIR.exists():
        shutil.rmtree(LUA_DIR)
    LUA_DIR.mkdir(parents=True, exist_ok=True)

    tile_files = sorted(TILES_DIR.glob("*.json"))
    if len(tile_files) != 102:
        raise SystemExit(f"Expected 102 Street V3 tile JSON files, found {len(tile_files)}")

    stats = []
    total_vertices = total_triangles = total_surface_tiles = total_skipped = 0

    for index, tile_path in enumerate(tile_files, start=1):
        data = load_json(tile_path)
        tile_id = str(data.get("tile_id") or data.get("id") or tile_path.stem)
        bounds = data.get("local_bounds_m") or {}
        min_x, min_z = float(bounds["min_x"]), float(bounds["min_z"])
        max_x, max_z = float(bounds["max_x"]), float(bounds["max_z"])
        tile_box = box(min_x, min_z, max_x, max_z)
        roads = (data.get("layers") or {}).get("roads", [])

        road_polys = []
        skipped = 0
        for feature in roads:
            props = feature.get("properties") or {}
            if clean(props.get("osm_bridge")) in BRIDGE_TRUE or clean(props.get("osm_tunnel")) in TUNNEL_TRUE:
                skipped += 1
                continue
            try:
                geom = shape(feature.get("geometry"))
            except Exception:
                continue
            width = road_width(props)
            for line in lines_from_geom(geom):
                if line.length < 0.4:
                    continue
                try:
                    poly = line.buffer(width / 2.0, cap_style=2, join_style=2, mitre_limit=3.0)
                except Exception:
                    continue
                if not poly.is_empty:
                    road_polys.append(poly)

        if not road_polys:
            stats.append({"tile": tile_id, "vertices": 0, "triangles": 0, "bridge_tunnel_skipped": skipped})
            total_skipped += skipped
            continue

        union = unary_union(road_polys).intersection(tile_box)
        triangles_xy = []
        for poly in polygons_from_geom(union):
            triangles_xy.extend(triangulate_polygon(poly))

        if not triangles_xy:
            stats.append({"tile": tile_id, "vertices": 0, "triangles": 0, "bridge_tunnel_skipped": skipped})
            total_skipped += skipped
            continue

        center_local_x = (min_x + max_x) / 2.0
        center_local_z = (min_z + max_z) / 2.0
        origin_x, origin_z = roblox_xz(center_local_x, center_local_z)
        vertex_map = {}
        vertices = []
        triangles = []

        def vertex_index(local_x, local_z):
            rx, rz = roblox_xz(local_x, local_z)
            key = (round(rx - origin_x, 3), round(rz - origin_z, 3))
            if key in vertex_map:
                return vertex_map[key]
            idx = len(vertices) + 1
            vertex_map[key] = idx
            vertices.append(key)
            return idx

        for tri in triangles_xy:
            ids = [vertex_index(*tri[0]), vertex_index(*tri[1]), vertex_index(*tri[2])]
            if len(set(ids)) == 3:
                triangles.append(tuple(ids))

        if len(vertices) > MAX_VERTICES_PER_TILE:
            raise RuntimeError(f"{tile_id} has {len(vertices):,} vertices; limit is {MAX_VERTICES_PER_TILE:,}")

        write_tile_module(LUA_DIR / f"{tile_id}.lua", tile_id, origin_x, origin_z, vertices, triangles)
        stats.append({"tile": tile_id, "vertices": len(vertices), "triangles": len(triangles), "bridge_tunnel_skipped": skipped})
        total_vertices += len(vertices)
        total_triangles += len(triangles)
        total_skipped += skipped
        total_surface_tiles += 1
        print(f"[{index:03d}/102] {tile_id}: {len(vertices):,} vertices / {len(triangles):,} triangles")

    if total_triangles > MAX_TOTAL_TRIANGLES:
        raise RuntimeError(f"V5 total triangle budget exceeded: {total_triangles:,} > {MAX_TOTAL_TRIANGLES:,}")

    report = {
        "schema": "chesterworld.street_surface.v5",
        "source_tiles": str(TILES_DIR),
        "tile_json_count": len(tile_files),
        "surface_tile_modules": total_surface_tiles,
        "total_vertices": total_vertices,
        "total_triangles": total_triangles,
        "bridge_tunnel_records_skipped": total_skipped,
        "max_vertices_per_tile": max((item["vertices"] for item in stats), default=0),
        "max_triangles_per_tile": max((item["triangles"] for item in stats), default=0),
        "budgets": {"max_vertices_per_tile": MAX_VERTICES_PER_TILE, "max_total_triangles": MAX_TOTAL_TRIANGLES},
        "tiles": stats,
    }
    REPORT.write_text(json.dumps(report, indent=2), encoding="utf-8")
    print()
    print("=" * 92)
    print("STREET SURFACE V5 DATA READY")
    print("=" * 92)
    print(f"Source tile JSON:        {len(tile_files):,}")
    print(f"Surface tile modules:    {total_surface_tiles:,}")
    print(f"Total vertices:          {total_vertices:,}")
    print(f"Total triangles:         {total_triangles:,}")
    print(f"Bridge/tunnel skipped:   {total_skipped:,}")
    print(f"Output Lua folder:       {LUA_DIR}")
    print(f"Report:                  {REPORT}")
    print("=" * 92)


if __name__ == "__main__":
    main()
