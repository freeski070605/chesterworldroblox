#!/usr/bin/env python3
"""Rebuild conservative OSM-to-game-ID associations from checked-in geometry."""
import argparse
import csv
import json
from pathlib import Path

from compare_building_alignment import candidates, old_polygon

MIN_IOU = 0.55
MIN_COVERAGE = 0.80
MIN_MARGIN = 0.10


def associate(existing, footprints):
    legacy = [(str(row["id"]), row["tile"], old_polygon(row)) for row in existing]
    results = []
    for item in footprints:
        polygon = item["polygon"]
        scores = []
        for game_id, tile, other in legacy:
            overlap = polygon.intersection(other).area
            if overlap <= 0:
                continue
            scores.append((overlap / polygon.union(other).area, overlap / polygon.area, game_id, tile))
        scores.sort(reverse=True)
        first = scores[0] if scores else (0, 0, None, None)
        second = scores[1] if len(scores) > 1 else (0, 0, None, None)
        status = "associated" if first[0] >= MIN_IOU and first[1] >= MIN_COVERAGE and first[0] - second[0] >= MIN_MARGIN else "review"
        if not scores:
            status = "unmatched_manual_review"
        results.append({"osmId": item["id"], "gameId": first[2] if status == "associated" else None,
                        "candidateGameId": first[2], "tile": first[3], "status": status,
                        "iou": round(first[0], 4), "coverage": round(first[1], 4),
                        "nextIou": round(second[0], 4), "candidateCount": len(scores),
                        "sourceRef": "https://www.openstreetmap.org/way/" + item["id"].split("_")[2]})
    # Multiple OSM footprints can overlap one oversized old rectangle. None
    # should silently claim the same gameplay ID.
    owners = {}
    for row in results:
        if row["gameId"]:
            owners.setdefault(row["gameId"], []).append(row)
    for tied in owners.values():
        if len(tied) > 1:
            for row in tied:
                row["status"] = "review_duplicate_game_id"
                row["gameId"] = None
    return results


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--existing", type=Path, default=Path("tools/reconstruction/data/chester_9th_kerlin_existing.csv"))
    parser.add_argument("--candidate", type=Path, default=Path("src/shared/ReconstructionPilot.lua"))
    parser.add_argument("--out", type=Path, default=Path("tools/reconstruction/data/chester_9th_kerlin_associations.json"))
    parser.add_argument("--luau", type=Path, default=Path("src/shared/ReconstructionAssociations.lua"))
    parser.add_argument("--review-luau", type=Path, default=Path("src/shared/ReconstructionReviewStatus.lua"))
    args = parser.parse_args()
    with args.existing.open(newline="", encoding="utf-8") as handle:
        rows = associate(list(csv.DictReader(handle)), candidates(args.candidate))
    report = {"method": "polygon IoU and candidate area coverage, unique game ID", "thresholds": {
        "minIou": MIN_IOU, "minCoverage": MIN_COVERAGE, "minMargin": MIN_MARGIN}, "rows": rows}
    args.out.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    lines = ["-- Generated by tools/reconstruction/build_associations.py; review JSON report.", "return {"]
    for row in rows:
        if row["gameId"]:
            lines.append(f'    ["{row["osmId"]}"] = "{row["gameId"]}",')
    lines.append("}\n")
    args.luau.write_text("\n".join(lines), encoding="utf-8")
    status_lines = [
        "-- Generated by tools/reconstruction/build_associations.py; source: association JSON report.",
        "-- Status is automated geometric review only, not a validated building identity.",
        "return {",
    ]
    for row in rows:
        status_lines.append(f'    ["{row["osmId"]}"] = "{row["status"]}",')
    status_lines.append("}\\n")
    args.review_luau.write_text("\\n".join(status_lines), encoding="utf-8")
    print(f"associated={sum(r['gameId'] is not None for r in rows)} review={sum(r['status'].startswith('review') for r in rows)} unmatched={sum(r['status'].startswith('unmatched') for r in rows)}")


if __name__ == "__main__":
    main()
